export function generateClientSideReport(payload) {
  const {
    user_type = '근로자',
    company_size = '5인 이상',
    salary_type = '월급',
    salary_amount = '2500000',
    issue_text = '',
    pattern1_days = 5,
    pattern1_hours = 8,
    break_time = 60,
    deduction_type = '4대보험'
  } = payload;

  const numSalary = parseFloat(salary_amount) || 0;
  const is5More = company_size.includes('5인 이상');
  
  // 1. 소정근로시간 & 최저임금 산정 (2026년 최저시급 10,320원)
  const monthlyHours = 209;
  const minHourly = 10320;
  const minMonthly = monthlyHours * minHourly; // 2,156,880원
  
  const estimatedHourly = salary_type === '시급' ? numSalary : (salary_type === '월급' ? Math.round(numSalary / monthlyHours) : 10320);
  const isBelowMin = estimatedHourly < minHourly;

  // 2. 가산수당 대상 판별
  const overtimeRate = is5More ? 1.5 : 1.0;

  return `
# 🤖 노무체크 AI 종합 법률 진단 리포트

## 📋 1. 기초 근로 조건 요약
- **진단 대상자 구별**: ${user_type}
- **사업장 규모**: ${company_size} (${is5More ? '근로기준법 전체 조항 적용' : '5인 미만 사업장: 해고 제한 및 가산수당 일부 예외'})
- **급여 책정 방식**: ${salary_type} (${numSalary.toLocaleString()}원)
- **추정 환산 시급**: 약 ${estimatedHourly.toLocaleString()}원 (${isBelowMin ? '⚠️ 최저임금 미달 우려' : '✅ 2026년 최저시급 10,320원 이상 준수'})

---

## ⚖️ 2. 법적 리포트 및 핵심 쟁점 분석

### 🔍 [쟁점 1] 최저임금 및 주휴수당 적법성
- **2026년 법정 최저시급**: 시간당 **10,320원** (주 40시간 소정근로 월 환산 209시간 기준 최저 기본월급 **2,156,880원**)
- **진단 결과**: ${isBelowMin ? `입력하신 급여(${numSalary.toLocaleString()}원)는 2026년 법정 최저임금에 미달할 위험이 큽니다. 미달된 차액은 최저임금법 제6조 위반으로 최근 3년 치 소급 청구가 가능합니다.` : '현재 설정된 급여 기준은 2026년 최저임금 법정 기준을 충족하고 있습니다.'}
- **주휴수당 법적 기준**: 주 소정근로시간이 15시간 이상이고 소정근로일을 개근한 경우 주 1회 이상의 유급휴일(8시간분 주휴수당)을 반드시 지급해야 합니다 (근로기준법 제55조).

### 🔍 [쟁점 2] 근로시간 및 가산수당 (5인 ${is5More ? '이상' : '미만'})
${is5More ? `- **연장·야간·휴일 가산수당**: 근로기준법 제56조에 따라 하루 8시간 또는 주 40시간을 초과하는 연장근로에 대해 **50% 가산(1.5배)**을 지급해야 합니다.
- **포괄임금제 무효 가능성**: 근로시간 산정이 곤란하지 않은 사무직·매장직의 경우 포괄임금 약정이 있더라도 실제 초과 근무수당 차액을 청구할 수 있습니다.` : `- **5인 미만 사업장 특례**: 근로기준법 제56조의 연장·야간·휴일 가산수당(1.5배) 부과 의무가 적용되지 않아 기본 시급(1.0배) 기준으로 정산될 수 있으나, 최저임금 및 주휴수당은 100% 적용됩니다.`}

---

## 📝 3. 입력된 상시 쟁점 사항 답변
> **사용자 문의/상세 사연**: "${issue_text || '기본 근로 조건 진단 요청'}"

### 💡 전문가 조언 및 맞춤 대안
1. **증빙 자료 확보**: 근로계약서, 임금명세서, 통장 입금 내역, 출퇴근 기록(문자, 교통카드, 출퇴근 앱 등)을 3년간 보관하세요.
2. **구제 및 해결 절차**: 
   - 근로자: 사업주와 우선 협의 후 조율되지 않을 경우 고용노동부 노동포털(labor.moel.go.kr)을 통해 진정서 접수 가능.
   - 사업주: 서면 근로계약서 작성을 완료하고, 최저임금 미달 요소를 즉시 수정하여 과태료 처분을 방지하세요.

---

## 💡 4. 실전 가이드 및 대응 단계

1. **근로계약서 서면 교부 여부 확인** (위반 시 500만원 이하 과태료)
2. **임금명세서 필수 항목 표기 여부 점검** (근로기준법 제48조)
3. **고용노동부 고객상담센터 1350 연결** (국번없이 1350 무료상담)

---
*본 리포트는 노무체크 AI 자동 진단 엔진이 근로기준법 조문을 기반으로 생성한 리포트이며, 개별 사건의 정식 법률 대리가 아닙니다.*
`;
}

